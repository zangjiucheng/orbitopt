"""E6-02 regression test: guided JSBSim ascent with staging (task #274).

Two halves:

* the committed benchmark JSON (``docs/benchmarks/e6_02_guided_ascent.json``,
  generated by ``benchmarks/bench_e6_02_guided_ascent.py``) must be internally
  consistent -- zero failed checks -- and its headline numbers must sit inside
  regression bands around the recorded mission;
* a short live run of the module on the JSBSim production path (coarse step,
  stack to MECO only, no children) must reproduce the committed stack-powered
  metrics inside those bands and pass its staging bookkeeping -- the flight,
  not just the file, is under test (skips without the ``jsbsim`` binding).
"""
from __future__ import annotations

import json
import math
from pathlib import Path

import pytest

pytest.importorskip("jsbsim")

REPO = Path(__file__).resolve().parents[1]
BENCH_JSON = REPO / "docs" / "benchmarks" / "e6_02_guided_ascent.json"

from orbitopt.flightlab.sixdof.guided_ascent import (  # noqa: E402
    PHASES, STACK_POWERED, e602_scenario, run_e602_study,
    run_guided_ascent_jsbsim)


@pytest.fixture(scope="module")
def bench() -> dict:
    if not BENCH_JSON.exists():
        pytest.skip(f"benchmark JSON not generated: {BENCH_JSON}")
    return json.loads(BENCH_JSON.read_text())


def test_committed_benchmark_all_green(bench: dict) -> None:
    assert bench["failed_checks"] == []
    assert bench["meta"]["all_checks_passed"] is True
    assert len(bench["checks"]) >= 38


def test_committed_benchmark_phase_blocks(bench: dict) -> None:
    for plant in ("jsbsim", "native"):
        assert set(bench["phases"][plant]) == set(PHASES)


def test_committed_stack_powered_bands(bench: dict) -> None:
    for plant, att_tol, alpha_tol, q_tol in (("jsbsim", 1.0, 2.0, 0.05),
                                            ("native", 1.5, 2.0, 0.05)):
        m = bench["phases"][plant][STACK_POWERED]
        ref = {"jsbsim": {"att": 0.44, "alpha": 11.7},
               "native": {"att": 4.26, "alpha": 11.6}}[plant]
        assert m["att_err_max_deg"] <= ref["att"] + att_tol
        assert abs(m["alpha_max_deg"] - ref["alpha"]) <= alpha_tol
        assert abs(m["max_q_pa"] / 71353.0 - 1.0) <= q_tol
        assert m["saturated_s"] == 0.0
        assert m["deflection_margin_min"] >= 0.90


def test_committed_separation_bookkeeping(bench: dict) -> None:
    for plant in ("jsbsim", "native"):
        bk = bench["bookkeeping"][plant]
        assert abs(bk["mass_residual_kg"]) <= 1e-3
        assert bk["position_continuity_err_m"] <= 1e-3
        # the property round-trip is plant-specific by construction: the
        # native split is exact, the JSBSim one carries the fps/Euler band
        vel_tol = 1e-6 if plant == "native" else 0.05
        assert bk["velocity_continuity_err_m_s"] <= vel_tol
    assert abs(bench["bookkeeping"]["jsbsim_ignition_onset_err_s"]) <= 0.03
    assert abs(bench["bookkeeping"]["native_ignition_onset_err_s"]) <= 0.3
    # the spike-engine upper burns out seconds after ignition, not minutes
    for plant in ("jsbsim", "native"):
        tb = bench["bookkeeping"][f"{plant}_upper_burnout_t_s"]
        assert 95.0 + 8.0 < tb < 95.0 + 8.0 + 12.0


def test_committed_comparison_channels(bench: dict) -> None:
    cats = bench["comparison"]
    assert set(cats) == {"dynamics", "guidance", "integration", "model"}
    for entries in cats.values():
        assert entries
    integ = {e["id"]: e["value"] for e in cats["integration"]}
    dt_shift = next(v for k, v in integ.items() if isinstance(v, dict))
    assert dt_shift["jsbsim_alt_rel"] <= 0.02
    assert dt_shift["native_alt_rel"] <= 0.002


def test_live_short_jsbsim_run_matches_committed() -> None:
    s = e602_scenario(dt_s=0.05, t_end_s=110.0)
    study = run_guided_ascent_jsbsim(s)
    m = study.phases[STACK_POWERED]
    assert m["att_err_max_deg"] <= 1.5           # committed 0.44 deg
    assert m["alpha_max_deg"] <= 14.0            # committed 11.7 deg
    assert abs(m["max_q_pa"] / 71353.0 - 1.0) <= 0.10
    assert m["saturated_s"] == 0.0
    for c in study.checks:
        assert c.passed, f"{c.id}: {c.value} vs {c.limit}"
