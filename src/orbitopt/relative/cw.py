"""Clohessy-Wiltshire (Hill) relative motion: the fast linear planning model (E12-02).

CW linearises the two-body problem about a *circular* chief orbit in the
LVLH frame of :mod:`orbitopt.relative.frames` (x radial outward, y
along-track, z cross-track -- the same axes, so the sign convention of the
Coriolis and gravity-gradient terms below is the one that frame implies):

    x'' - 2 n y' - 3 n^2 x = 0
    y'' + 2 n x'           = 0
    z'' + n^2 z            = 0

with ``n`` the chief's circular mean motion. The closed-form state
transition matrix here is the standard CW solution, verified against RK4
integration of the equations themselves (tests/test_e12_02_relative_dynamics.py).

Scope: this is a *planning* model, not an acceptance model. It is exact
under its own linearisation only: for a real two-body pair its error grows
with initial separation, propagation time and chief eccentricity (there is
no valid CW for e > 0 at all -- ``n`` alone cannot describe an eccentric
orbit's varying rate), and J2 is entirely absent. The committed evidence
for where that boundary lies is
``docs/benchmarks/e12_02_cw_validity.json`` (regenerated by
``benchmarks/bench_e12_02_cw_validity.py``): use CW inside the envelope,
and :func:`orbitopt.relative.propagation.propagate_pair` (nonlinear,
two-body + optional J2) for anything a mission decision hangs on.
"""
from __future__ import annotations

import math

import numpy as np

from orbitopt.physics_io import (
    MAX_DURATION_S,
    RELATIVE_STATE,
    UnitMismatchError,
    check_positions,
    check_velocities,
)

MU_EARTH = 3.9860044150e14  # m^3/s^2 -- the frame the envelopes were measured in


def mean_motion_circular(mu: float, radius: float) -> float:
    """Circular mean motion ``n = sqrt(mu / r^3)`` [rad/s] for a chief on a
    circle of ``radius`` [m] about a body with parameter ``mu`` [m^3/s^2] --
    the CW module's only orbit input."""
    mu = float(mu)
    r = float(radius)
    if not (math.isfinite(mu) and mu > 0.0):
        raise ValueError(f"mu must be finite and > 0, got {mu!r}")
    if not (math.isfinite(r) and r > 0.0):
        raise ValueError(f"chief orbital radius must be finite and > 0, got {radius!r}")
    return math.sqrt(mu / r ** 3)


def cw_state_transition(n, t):
    """The 6x6 Clohessy-Wiltshire state transition matrix for state ordering
    ``(x, y, z, x_dot, y_dot, z_dot)`` in LVLH metres and m/s, chief mean
    motion ``n`` [rad/s] and elapsed time ``t`` [s].

    ``t`` may be a scalar (returns ``(6, 6)``) or an array (returns
    ``t.shape + (6, 6)``) -- the batched form is what a multi-burn CW
    targeting loop consumes. ``n`` is scalar.
    """
    n = float(n)
    if not (math.isfinite(n) and n > 0.0):
        raise ValueError(f"chief mean motion n must be finite and > 0, got {n!r}")
    tt = np.asarray(t, dtype=np.float64)
    if not np.all(np.isfinite(tt)):
        raise ValueError("CW transition time must be finite")
    if tt.ndim == 0:
        tt = tt.reshape(())
    nt = n * tt
    c = np.cos(nt)
    s = np.sin(nt)
    z = np.zeros_like(nt)
    one = np.ones_like(nt)

    def row(*elems):
        return np.stack(tuple(np.broadcast_to(np.asarray(e, dtype=np.float64), nt.shape)
                              for e in elems), axis=-1)

    phi = np.empty(nt.shape + (6, 6), dtype=np.float64)
    phi[..., 0, :] = row(4 - 3 * c, z, z, s / n, 2 * (1 - c) / n, z)
    phi[..., 1, :] = row(6 * (s - nt), one, z, -2 * (1 - c) / n, (4 * s - 3 * nt) / n, z)
    phi[..., 2, :] = row(z, z, c, z, z, s / n)
    phi[..., 3, :] = row(3 * n * s, z, z, c, 2 * s, z)
    phi[..., 4, :] = row(-6 * n * (1 - c), z, z, -2 * s, 4 * c - 3, z)
    phi[..., 5, :] = row(z, z, -n * s, z, z, c)
    return phi


def propagate_cw(rho, rho_dot, n, t, *, where: str = ""):
    """Propagate a LVLH relative state (position ``rho`` [m], LVLH rate
    ``rho_dot`` [m/s], each ``(3,)`` or ``(N,3)``) by the closed-form CW
    solution over elapsed ``t`` [s] (scalar, or one duration per row).
    Returns ``(rho_t, rho_dot_t)`` with the leading shape broadcast of the
    inputs and ``t``.

    Checks the initial state against :data:`orbitopt.physics_io.RELATIVE_STATE`
    (chief-centred metres, separation band, no silent unit assumptions); the
    *output* is not band-checked because CW legitimately carries a large
    along-track drift for a separation outside the validity envelope -- that
    is precisely what the envelope is there to bound.
    """
    n = float(n)
    if not (math.isfinite(n) and n > 0.0):
        raise ValueError(f"chief mean motion n must be finite and > 0, got {n!r}")
    r = np.asarray(rho, dtype=np.float64)
    v = np.asarray(rho_dot, dtype=np.float64)
    if r.shape != v.shape:
        raise ValueError(f"rho and rho_dot must have the same shape, got {r.shape} vs {v.shape}")
    if r.ndim == 0 or r.shape[-1:] != (3,):
        raise ValueError(f"rho must be (3,) or (N,3), got shape {r.shape}")
    if not (np.all(np.isfinite(r)) and np.all(np.isfinite(v))):
        raise ValueError("CW initial relative state must be finite")
    check_positions(r, units=RELATIVE_STATE.units, radius_range=RELATIVE_STATE.position_range,
                    centre="chief", where=where or "propagate_cw: rho")
    check_velocities(v, units=RELATIVE_STATE.units, speed_range=RELATIVE_STATE.velocity_range,
                     centre="chief", where=where or "propagate_cw: rho_dot")
    tt = np.asarray(t, dtype=np.float64)
    if not np.all(np.isfinite(tt)):
        raise ValueError(f"{where or 'propagate_cw'}: propagation times must be finite")
    if np.any(np.abs(tt) > MAX_DURATION_S):
        raise UnitMismatchError(
            f"{where or 'propagate_cw'}: duration exceeds {MAX_DURATION_S:.0e} s "
            "(3000 years) -- a days/hertz/radians mix-up, not a rendezvous."
        )
    lead_in = r.shape[:-1]
    if tt.ndim and lead_in != () and tt.shape != lead_in:
        raise ValueError(f"{where or 'propagate_cw'}: t must be a scalar or one duration per "
                         f"state row, got shape {tt.shape} for state {r.shape}")
    lead = lead_in if lead_in != () else tt.shape
    state = np.broadcast_to(np.concatenate((r, v), axis=-1), lead + (6,)).reshape(-1, 6)
    tf = np.broadcast_to(tt, lead).reshape(-1)
    phi = cw_state_transition(n, tf)
    out = np.einsum("...j,...ij->...i", state, phi).reshape(lead + (6,))
    return out[..., :3].copy(), out[..., 3:].copy()
